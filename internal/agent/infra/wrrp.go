func IDFromPublicKey(pubKey string) ([32]byte, error) {
	key, err := wgtypes.ParseKey(pubKey)
	if err != nil {
		return [32]byte{}, err
	}
	return key, nil
}

// lrpFakePrefix is the fixed /96 ULA prefix used to encode LRP remote IDs
// as fake IPv6 addresses for display in wg show.
//
// "fd6c:7270:0000::" — "fd" (ULA) + "lr"(6c72) + "p"(7000).
// The lower 8 bytes carry the 64-bit RemoteId in big-endian order.
var lrpFakePrefix = [8]byte{0xfd, 0x6c, 0x72, 0x70, 0x00, 0x00, 0x00, 0x00}

const LrpFakePort = 51820

// LrpFakeAddrPort encodes a LRP RemoteId as a fake IPv6 AddrPort.
// The resulting address looks like fd6c:7270:0000:0:<hi>:<hi>:<lo>:<lo>
// and is safe to pass to wg show / UAPI because it parses as a valid IP:port.
func LrpFakeAddrPort(remoteId uint64) netip.AddrPort {
	var b [16]byte
	copy(b[:8], lrpFakePrefix[:])
	binary.BigEndian.PutUint64(b[8:], remoteId)
	return netip.AddrPortFrom(netip.AddrFrom16(b), LrpFakePort)
}

// IsLrpFakeAddr reports whether addr was generated by LrpFakeAddrPort.
func IsLrpFakeAddr(addr netip.Addr) bool {
	if !addr.Is6() {
		return false
	}
	b := addr.As16()
	return b[0] == lrpFakePrefix[0] &&
		b[1] == lrpFakePrefix[1] &&
		b[2] == lrpFakePrefix[2] &&
		b[3] == lrpFakePrefix[3] &&
		b[4] == lrpFakePrefix[4] &&
		b[5] == lrpFakePrefix[5]
}

// RemoteIdFromLrpFakeAddr extracts the RemoteId encoded in a fake LRP address.
func RemoteIdFromLrpFakeAddr(addr netip.Addr) uint64 {
	b := addr.As16()
	return binary.BigEndian.Uint64(b[8:])
}

// 1. 自定义一个极简的 Endpoint
type LRPEndpoint struct {
	// 物理层信息 (用于标准 UDP/ICE)
	Addr netip.AddrPort

	// 协议层信息 (用于 LRP)
	RemoteId uint64

	// 标志位：当前该走哪条路
	TransportType TransportType
}

func (e *LRPEndpoint) ClearSrc() {

}

func (e *LRPEndpoint) Clear() {}
func (e *LRPEndpoint) DstToString() string {
	// For display purposes (wg show / UAPI GET), always prefer the physical
	// relay address when available.  Routing is driven by DstToBytes() (which
	// uses RemoteId for LRP) and Send() (which checks TransportType), so
	// returning the relay IP:port here does not affect the data plane.
	if e.Addr.IsValid() {
		return e.Addr.String()
	}
	// Fallback: should not normally be reached because ReceiveFunc always sets
	// Addr to LrpFakeAddrPort(RemoteId).
	return fmt.Sprintf("lrp://%d", e.RemoteId)
}

func (e *LRPEndpoint) DstToBytes() []byte {
	if e.TransportType == LRP {
		b := make([]byte, 8)
		binary.BigEndian.PutUint64(b, e.RemoteId)
		return b
	}
	// 标准 UDP 模式下，AddrPort 转换为字节
	b, _ := e.Addr.MarshalBinary()
	return b
}

func (e *LRPEndpoint) DstIP() netip.Addr {
	if e.TransportType == LRP {
		// LRP 路由完全由 RemoteId 决定，不走 UDP 路径，
		// 返回 loopback 供 WireGuard 内部速率限制使用。
		return netip.IPv4Unspecified()
	}
	return e.Addr.Addr()
}

func (e *LRPEndpoint) SrcIP() netip.Addr {
	return netip.Addr{}
}
func (e *LRPEndpoint) SrcToString() string { return "" }
